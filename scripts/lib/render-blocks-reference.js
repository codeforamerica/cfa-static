/** Pure block documentation rendering, shared by the CLI and freshness tests. */
import { stringify } from "yaml";
import { componentNameFor } from "#scripts/customise-cms/blocks.js";
import {
  escapeText,
  fencedCode,
  inlineCode,
  markdownTable,
} from "#scripts/lib/markdown.js";
import { isColumnSafeType } from "#utils/block-columns.js";
import { CONTAINER_FIELDS } from "#utils/block-schema/shared.js";
import {
  BLOCK_DOCS,
  BLOCK_EXAMPLES,
  BLOCK_SCHEMAS,
  getBlockContainerWidth,
  getBlockTemplate,
  validateBlocks,
} from "#utils/block-schema.js";

/** @typedef {import("#scripts/customise-cms/blocks.js").BlockFieldSchema & { description?: string, allowPipeDelimitedItems?: boolean }} DocField */

// Shared field factories type nested fields as plain objects; the registry holds schemas.
const FIELD_SCHEMAS = /** @type {Record<string, Record<string, DocField>>} */ (
  BLOCK_SCHEMAS
);

/** @param {DocField} field */
const fieldDescription = (field) =>
  [
    field.description,
    field.allowPipeDelimitedItems ? 'Also accepts "value|label" strings.' : "",
    field.options ? `CMS options: ${JSON.stringify(field.options)}` : "",
  ]
    .filter(Boolean)
    .join(" ");

/** @param {string} path @param {DocField} field */
const renderFieldRow = (path, field) => {
  const type = field.list ? `array<${field.type}>` : field.type;
  const defaultText = field.default === "" ? '""' : field.default;
  return [
    inlineCode(path),
    inlineCode(type),
    field.required ? "**required**" : "optional",
    defaultText === undefined ? "Not documented" : inlineCode(defaultText),
    field.label === undefined ? "Not exposed" : escapeText(field.label),
    escapeText(fieldDescription(field)),
  ];
};

/**
 * @param {string} [prefix]
 * @returns {(entry: [string, DocField]) => string[][]}
 */
const fieldRows =
  (prefix = "") =>
  ([key, field]) => {
    const path = `${prefix}${key}`;
    const childPrefix = `${path}${field.list ? "[]" : ""}.`;
    return [
      renderFieldRow(path, field),
      ...(field.fields
        ? Object.entries(field.fields).flatMap(fieldRows(childPrefix))
        : []),
    ];
  };

/** Render full field schemas, retaining nested required flags and falsy defaults.
 * @param {Record<string, DocField>} fields
 */
export const renderFieldTable = (fields) =>
  markdownTable(
    [
      "Field",
      "Schema type",
      "Presence",
      "Documented default",
      "CMS label",
      "Description",
    ],
    Object.entries(fields).flatMap(fieldRows()),
  );

/** @param {string} type */
const columnCompatibility = (type) => (isColumnSafeType(type) ? "Yes" : "No");

/** @param {(typeof BLOCK_EXAMPLES)[number]} entry */
const validateCanonicalExample = ({ type, example }) => {
  if (!BLOCK_DOCS[type]?.summary || !example) {
    throw new Error(`Missing documentation or canonical example for ${type}`);
  }
  if (example.type !== type) {
    throw new Error(
      `Canonical example type must match registry type "${type}"`,
    );
  }
  validateBlocks([example], ` in canonical example for ${type}`);
};

/** @param {(typeof BLOCK_EXAMPLES)[number]} entry */
const renderBlock = ({ type, collections, example }) => {
  const doc = BLOCK_DOCS[type];
  const yaml = stringify({ blocks: [example] }).trimEnd();
  return [
    `## ${inlineCode(type)}`,
    escapeText(doc.summary),
    `**Schema:** ${inlineCode(`src/_lib/utils/block-schema/${type}.js`)}`,
    `**Component:** ${inlineCode(componentNameFor(type))}`,
    `**Template:** ${inlineCode(`src/_includes/${getBlockTemplate(type)}`)}`,
    ...(doc.scss ? [`**SCSS:** ${inlineCode(doc.scss)}`] : []),
    ...(doc.htmlRoot ? [`**HTML root:** ${inlineCode(doc.htmlRoot)}`] : []),
    `**Container width:** ${inlineCode(getBlockContainerWidth(type))}`,
    `**CMS collection availability:** ${collections === null ? "All collections with a block editor" : collections.map(inlineCode).join(", ")}`,
    `**Columns / sidebar:** ${columnCompatibility(type)}`,
    Object.keys(BLOCK_SCHEMAS[type]).length > 0
      ? renderFieldTable(FIELD_SCHEMAS[type])
      : "No block-specific fields. Common fields still apply.",
    ...(doc.notes ? [`**Usage notes:** ${escapeText(doc.notes)}`] : []),
    "### Canonical example",
    fencedCode(yaml, "yaml"),
  ].join("\n\n");
};

const REFERENCE_INTRO = [
  "# Block Reference",
  "<!-- Generated by scripts/generate-blocks-reference.js. Do not edit by hand. -->",
  "Blocks are entries in a YAML frontmatter `blocks:` array. This reference is generated from the full field schemas and canonical `BLOCK_EXAMPLES`, in deliberate registry order. Regenerate with `npm run generate-references`, or `npm run generate-blocks-reference` for this file alone.",
  "See [Layouts](layouts.md) for rendering architecture, column matching, sidebar behavior, and styling. All source paths below are repository-root-relative.",
  "## Reading the schemas",
  "Schema types retain authoring semantics: `markdown`, `image`, and `reference` store strings; `array<T>` is a list of T. Dotted paths describe nested objects, and `[]` describes each list item. A required child is required only when its optional parent object is supplied (or for each supplied list object). Required fields must be supplied even when a documented default is shown.",
  "The **Documented default** column reproduces display-text metadata, not executable typed defaults. It neither inserts values into YAML nor changes validation. `Not documented` means no default metadata exists. Copy the canonical examples, not default text, for executable YAML. Descriptions and usage notes may describe contextual/template behavior beyond schema validation.",
  "**CMS collection availability** describes the schema's editor allowlist, not a runtime restriction. Site CMS customization can hide collections or blocks. Contextual blocks may still need page data to render usefully. **CMS label** identifies editor-exposed fields; `Not exposed` fields can still be authored in YAML.",
].join("\n\n");

export const renderBlocksReference = (examples = BLOCK_EXAMPLES) => {
  const types = Object.keys(BLOCK_SCHEMAS);
  if (types.join("\n") !== examples.map(({ type }) => type).join("\n")) {
    throw new Error(
      "Block schemas and canonical examples must have identical registry order",
    );
  }
  for (const entry of examples) validateCanonicalExample(entry);
  return `${[
    REFERENCE_INTRO,
    "## Common fields",
    "`type` is a required string selecting a registered block. The common wrapper fields below come from `CONTAINER_FIELDS`. `dark` selects a dark section palette; `compact` reduces section padding. They affect full-width section wrappers, not direct column/sidebar rendering; transparent `snippet` blocks do not acquire their own wrapper.",
    renderFieldTable(CONTAINER_FIELDS),
    "## Column and sidebar compatibility",
    "This table covers registered types only. `No` types are rejected inside columns and the right-content sidebar, but may appear in full-width `before` slots. `Yes` means the type passes the placement check, not that it is context-free. Snippets are reusable compositions: keep their contents appropriate for their destination too.",
    markdownTable(
      ["Block", "Container width", "Columns / sidebar"],
      types.map((type) => [
        `[${inlineCode(type)}](#${type})`,
        inlineCode(getBlockContainerWidth(type)),
        columnCompatibility(type),
      ]),
    ),
    ...examples.map(renderBlock),
  ].join("\n\n")}\n`;
};
